# TASCAM SS-CDR250N / SS-R250N / SS-R300N RS-232C/TELNET protocol (TEAC, Ver. 2.00): on the network the
# machine ID "0", a two-character command and its data, ended by CR LF; on RS-232C the same preceded by LF
# and ended by CR. Numbers travel as tens, ones, thousands, hundreds ("2301" is 123).


def _ts(command, input, wire, **extra):
    text(TS, command, input, wire, **extra)


def _tsv(command, input, wire, reply, value, **extra):
    text(TS, command, input, wire, device_reply=reply + "\r\n",
         expect_result={"ok": {"kind": "value", "value": value}}, **extra)


