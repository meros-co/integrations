DPO_OK = {"ok": {"kind": "ack"}}
DPO_ERR = {"error": {"error": "device_error"}}


def dpo(command, input, wire, **extra):
    text(DPO, command, input, wire, **extra)


def dpo_state(path, value):
    out = value
    for part in reversed(path.split(".")):
        out = {part: out}
    return out


