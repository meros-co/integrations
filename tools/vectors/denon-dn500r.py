DR = "denon-dn500r"
# Denon Professional DN-500R serial command protocol (Manual Version 1.1): "@0", the command, CR, on RS-232C. Each
# command is answered with the ACK byte (06H) or NACK (15H); a status request with ACK, then the status, "@0" + code
# + CR.
_DR_SERIAL = {"serial_port": "COM3"}
_DR_OK = {"ok": {"kind": "ack"}}


def _dr(command, input, wire, **extra):
    text(DR, command, input, wire, settings=_DR_SERIAL, device_reply="\x06", expect_result=_DR_OK, **extra)


def _drs(command, input, wire, **extra):
    # A set followed by its request: each is answered ACK, the request then with the status.
    text(DR, command, input, wire, settings=_DR_SERIAL, device_reply="\x06\x06", expect_result=_DR_OK, **extra)


def _drv(command, wire, status, value, input=None, **extra):
    text(DR, command, input or {}, wire, settings=_DR_SERIAL, device_reply="\x06" + status + "\r",
         expect_result={"ok": {"kind": "value", "value": value}}, **extra)


def _drt(name, inbound, state, **extra):
    telemetry(DR, name, settings=_DR_SERIAL, inbound=inbound, expect_state=state, **extra)


