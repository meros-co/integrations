def av(command, input, line, **extra):
    text(AV, command, input, line + "\r", **extra)


def av_v(command, input, line, reply, value, **extra):
    av(command, input, line, device_reply=reply + "\r\n",
       expect_result={"ok": {"kind": "value", "value": value}}, **extra)


