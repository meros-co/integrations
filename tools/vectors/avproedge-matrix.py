# HDBT manual p.22-23): SET/GET commands ended by a return (CR); answers are
# the command without SET or GET (manual p.26: GET DHCP -> DHCP 0). Expected
# lines are written from the command lists.
AV_OK = {"ok": {"kind": "ack"}}
