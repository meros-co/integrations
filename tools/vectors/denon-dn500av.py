# Denon Professional DN-500AV serial remote control (owner's manual pp.89-109): a two-character command and its
# parameter, then CR, on RS-232C or TCP 23. A request (command + "?") is answered in the form that sets it; control
# commands are not acknowledged.


def _av(command, input, wire, **extra):
    text(AV, command, input, wire, **extra)


def _avv(command, input, wire, reply, value):
    text(AV, command, input, wire, device_reply=reply, expect_result={"ok": {"kind": "value", "value": value}})


def _avt(name, inbound, state, **extra):
    telemetry(AV, name, inbound=inbound, expect_state=state, **extra)


