# Sharp professional displays' S-Format command protocol, over TCP 10008. Wire formats from Sharp's
# S-Format command manuals (PN-LA862/752/652 pp.2-9, PN-HW2 series, PN-M2/P6): four upper-case characters
# and a four-character parameter, ended by CR; a set answered OK (or WAIT, then OK), a read (????) by the
# value; every reply ended by CR LF. Each set is followed by its read, which updates state.
SH = "sharp-display"


def _sh(command, input, wire, replies, result, file=None, model=None):
    extra = {"file": file} if file else {}
    if model:
        extra["model"] = model
    text(SH, command, input, wire, device_reply="".join(replies), expect_result=result, **extra)


def _v(value):
    return {"ok": {"kind": "value", "value": value}}


