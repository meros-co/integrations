TB = "tascam-bd-mp1"
# TASCAM BD-MP1 / BD-MP1MKII RS-232C/ETHERNET protocol (TEAC, Ver. 1.04 and Ver. 1.00): "!", the unit type 7, a
# three-character command and its parameter, then CR. Every message is answered "ack" (or "nack"); a status request
# is answered "ack" and then the status, "!7" + the command + its value.
_OK = {"ok": {"kind": "ack"}}


def _tb(command, input, wire, **extra):
    text(TB, command, input, wire, device_reply="ack", expect_result=_OK, **extra)


def _tbs(command, input, wire, **extra):
    # A set followed by its request: each is answered ack, the request then with the status.
    text(TB, command, input, wire, device_reply="ackack", expect_result=_OK, **extra)


def _tbv(command, wire, status, value, **extra):
    text(TB, command, {}, wire, device_reply="ack" + status + "\r",
         expect_result={"ok": {"kind": "value", "value": value}}, **extra)


