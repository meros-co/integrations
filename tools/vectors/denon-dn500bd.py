DB = "denon-dn500bd"
# Denon Professional DN-500BD ([DV04] guide Ver. 2.00) and DN-500BD MKII (guide v1.1): "@0", the command, CR, on
# RS-232C or TCP 9030. Each command is answered with the ACK byte (06H) or NACK (15H); a status request with ACK,
# then the status, "@0" + code + CR.
_DB_OK = {"ok": {"kind": "ack"}}


def _db(command, input, wire, **extra):
    text(DB, command, input, wire, device_reply="\x06", expect_result=_DB_OK, **extra)


def _dbs(command, input, wire, **extra):
    # A set followed by its request (DN-500BD): each is answered ACK, the request then with the status.
    text(DB, command, input, wire, device_reply="\x06\x06", expect_result=_DB_OK, **extra)


def _dbv(command, wire, status, value, input=None, **extra):
    text(DB, command, input or {}, wire, device_reply="\x06" + status + "\r",
         expect_result={"ok": {"kind": "value", "value": value}}, **extra)


