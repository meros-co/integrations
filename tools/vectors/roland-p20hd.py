R20 = "roland-p20hd"
# Roland P-20HD (Reference Manual v2.00, edition 02, p.77-78): STX (02H) +
# code + ":" arguments + ";" with no line ending; operation commands are
# acknowledged by the byte ACK (06H) or refused with NAK (15H); inquiries are
# answered by their data frame alone.
R20_OK = {"ok": {"kind": "ack"}}


def r20(command, input, wire, **extra):
    text(R20, command, input, wire, **extra)


def r20v(command, input, wire, reply, value):
    text(R20, command, input, wire, device_reply=reply, expect_result={"ok": {"kind": "value", "value": value}})


