//! The model families of NEC's Projector Control Command Reference Manual
//! (BDT140013 rev. 7.1) and its appendixes (BDT140014 rev. 20.0), and of
//! Sharp NEC's edition (VDT24004 rev. 1.0, appendixes VDT24005 rev. 4.0):
//! for each, the commands its "Supported Command List" marks supported, and
//! the values its "Supplementary Information by Command" tables give for
//! the input terminals (018), the eco or light mode (097-8, 098-8), the
//! aspect (030-12) and the picture-in-picture sub input (097-198, 098-198).
//! Each family is one model of specs/nec-projector.yaml, by the same id.

pub(crate) struct Family {
    pub id: &'static str,
    /// Described by the 2024 edition, whose error bits, light information
    /// and signal types differ from the 2020 edition's.
    pub gen2024: bool,
    /// Command numbers the family supports, as the manual numbers them.
    pub commands: &'static [&'static str],
    pub inputs: &'static [(&'static str, u8)],
    pub eco: &'static [(&'static str, u8)],
    pub aspect: &'static [(&'static str, u8)],
    pub sub_inputs: &'static [(&'static str, u8)],
    /// The input terminal values of 319-10 AUDIO SELECT SET.
    pub audio: &'static [(&'static str, u8)],
}

impl Family {
    pub fn supports(&self, number: &str) -> bool {
        self.commands.contains(&number)
    }
}

